/**
 * Metadata-driven CRUD + validation spec generator.
 *
 * ZERO hardcoded flows or per-module values: every locator, field, value and
 * emitted test comes from what is extracted out of the module's OWN source —
 *   - data-testids            → extractCodeVocabulary (list + detail HTML)
 *   - form fields & widgets   → extractFormSchema via prepareModuleTestCase
 *   - test data               → business rules (Validators.*) via schema defaults
 *   - route                   → extractRouteHints (router config / routerLink)
 *   - row/edit/view/delete/search controls → testid suffix conventions found in
 *     the indexed list template (…-row, …-edit, …-view, …-delete, …-search)
 *   - delete confirmation     → confirm testid parsed from the shared
 *     confirmation dialog component (passed in as options.confirmTestId)
 *
 * A CRUD phase is only emitted when its metadata exists (no edit testid → no
 * edit test), so the generator stays truthful for any module shape.
 */

import { extractCodeVocabulary, resolveVerifyNeedle } from '../rag/ground.js';
import { prepareModuleTestCase } from '../rag/testCasePipeline.js';
import { pickIdentityFieldFromSchema } from '../rag/askAnalyzer.js';
import { extractRouteHints } from './codegen.js';

function slugify(name) {
  return String(name || 'module').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

/** Find a testid by suffix in extracted vocab (convention metadata, not hardcode). */
function tidBySuffix(vocab, suffix) {
  return (vocab.testIds || []).find((id) => id.endsWith(suffix)) || null;
}

/** Detail HTML declares a save gate ([disabled]="….invalid…") → validation test is grounded. */
function hasSaveGate(codeContext) {
  return /\[disabled\]="[^"]*invalid/i.test(String(codeContext || ''));
}

function q(s) {
  return JSON.stringify(String(s ?? ''));
}

/**
 * Build one self-contained Playwright spec covering Create → View → Edit →
 * Validation → Delete for a module, from its code context alone.
 */
export function buildModuleCrudSpec({ codeContext, feature, options = {} }) {
  const vocab = extractCodeVocabulary(codeContext || '');
  const prepared = prepareModuleTestCase({
    codeContext,
    title: `create a ${feature}`,
    description: `create a ${feature}`,
    matchedFeature: feature,
    intent: { action: 'create' },
  });

  const schema = prepared.schema;
  const fields = prepared.automationFields || [];
  const route = options.route || extractRouteHints(codeContext, feature);
  const stem = prepared.entityStem || slugify(feature);

  const createTid = tidBySuffix(vocab, '-create');
  const saveTid = tidBySuffix(vocab, '-save');
  const editTid = tidBySuffix(vocab, '-edit');
  const viewTid = tidBySuffix(vocab, '-view');
  const rowTid = tidBySuffix(vocab, '-row');
  const deleteTid = tidBySuffix(vocab, '-delete');
  const cancelTid = tidBySuffix(vocab, '-cancel');
  const searchTid = tidBySuffix(vocab, '-search');
  const emptyTid = tidBySuffix(vocab, '-empty-state');
  const confirmTid = options.confirmTestId || null;
  const searchControl = (vocab.formControls || []).find((fc) => /search|query/i.test(fc)) || null;

  const identity = pickIdentityFieldFromSchema(schema);
  const identityKey = prepared.testData.primaryField || identity?.key
    || fields.find((f) => f.kind === 'fill')?.formControl;
  const identityField = fields.find((f) => f.formControl === identityKey)
    || fields.find((f) => f.kind === 'fill');
  const identityTid = identityField?.testId || null;

  if (!createTid || !saveTid || !identityTid) {
    throw new Error(
      `${feature}: missing metadata for CRUD generation `
      + `(create=${createTid}, save=${saveTid}, identity=${identityTid}). `
      + 'Check that list+detail templates with data-testids are in the code context.',
    );
  }

  const requiredFields = (schema.fields || []).filter((f) => f.required);
  const gate = hasSaveGate(codeContext);
  const searchOpts = JSON.stringify({
    testId: searchTid,
    control: searchControl,
    route,
  });
  const rowSel = rowTid
    ? `[data-testid="${rowTid}"], table tbody tr, .mat-mdc-row, .mat-row`
    : 'table tbody tr, [data-testid$="-row"], .mat-mdc-row, .mat-row';

  const L = [];
  const put = (line = '') => L.push(line);

  put('// Auto-generated by Nocta QA (metadata-driven CRUD suite) — do not hand-edit.');
  put('// Regenerate: npm run e2e:generate · Run: npm run e2e:crud -- --headed');
  put('// (equivalent: npx playwright test --config generated-e2e/playwright.config.mjs <name> --headed)');
  put(`// Module: ${feature} · route ${route} · ${fields.length} form field(s), ${requiredFields.length} required (from Validators.*)`);
  put('// Requires TARGET_APP_URL, APP_TEST_USERNAME, APP_TEST_PASSWORD (auth.setup fast path supported).');
  put("import { test, expect } from '@playwright/test';");
  put("import { ensureCapboSession, fillAngularField, selectMatDropdown, searchList } from './helpers/capbo-ui';");
  put('');
  put('// Serial: View/Edit/Delete operate on the record Create makes.');
  put("test.describe.configure({ mode: 'serial' });");
  put('');
  put(`test.describe(${q(`${feature} CRUD`)}, () => {`);
  put('  test.setTimeout(45_000);');
  put('  const suffix = Date.now().toString(36).slice(-5);');
  put(`  const name = \`e2e-${slugify(stem)}-\${suffix}\`;`);
  put('  const updatedName = `${name}-upd`;');
  put('');

  // ---- CREATE ----
  put(`  test('Create ${feature} with all required fields', async ({ page }) => {`);
  put(`    await ensureCapboSession(page, ${q(route)});`);
  put(`    await page.getByTestId(${q(createTid)}).click({ timeout: 15000 });`);
  put('');
  for (const f of fields) {
    const label = f.label || f.formControl;
    if (!f.testId) continue; // testid-first policy: no guessing
    if (f.kind === 'select') {
      put(`    // ${label} — ${f.componentType || 'dropdown'} (${f.formControl})`);
      put(`    await selectMatDropdown(page, page.getByTestId(${q(f.testId)}), ${q(f.value)});`);
    } else {
      const value = f.formControl === identityKey ? '${name}' : null;
      put(`    // ${label} — ${f.componentType || 'input'} (${f.formControl})`);
      if (value) {
        put(`    await fillAngularField(page, page.getByTestId(${q(f.testId)}), name);`);
      } else {
        put(`    await fillAngularField(page, page.getByTestId(${q(f.testId)}), ${q(f.value)});`);
      }
    }
  }
  put('');
  if (gate) {
    put(`    const save = page.getByTestId(${q(saveTid)});`);
    put("    await expect(save, 'save must enable once required controls are valid').toBeEnabled({ timeout: 8000 });");
    put('    await save.click({ timeout: 15000 });');
  } else {
    put(`    await page.getByTestId(${q(saveTid)}).click({ timeout: 15000 });`);
  }
  put('');
  put(`    await searchList(page, name, ${searchOpts});`);
  put(`    await expect(page.locator(${q(rowSel)}).filter({ hasText: name }).first()).toBeVisible({ timeout: 15000 });`);
  put('  });');
  put('');

  // ---- VIEW (only when the list exposes a view control) ----
  if (viewTid) {
    put(`  test('View created ${feature}', async ({ page }) => {`);
    put(`    await ensureCapboSession(page, ${q(route)});`);
    put(`    await searchList(page, name, ${searchOpts});`);
    put(`    await page.locator(${q(rowSel)}).filter({ hasText: name }).first().getByTestId(${q(viewTid)}).or(page.getByTestId(${q(viewTid)}).first()).first().click({ timeout: 10000 });`);
    put(`    await expect(page.getByTestId(${q(identityTid)})).toHaveValue(name, { timeout: 10000 });`);
    put('  });');
    put('');
  }

  // ---- EDIT ----
  if (editTid) {
    put(`  test('Edit ${feature} (${identityKey})', async ({ page }) => {`);
    put(`    await ensureCapboSession(page, ${q(route)});`);
    put(`    await searchList(page, name, ${searchOpts});`);
    put(`    await page.locator(${q(rowSel)}).filter({ hasText: name }).first().getByTestId(${q(editTid)}).or(page.getByTestId(${q(editTid)}).first()).first().click({ timeout: 10000 });`);
    put(`    await fillAngularField(page, page.getByTestId(${q(identityTid)}), updatedName);`);
    put(`    await page.getByTestId(${q(saveTid)}).click({ timeout: 15000 });`);
    put(`    await searchList(page, updatedName, ${searchOpts});`);
    put(`    await expect(page.locator(${q(rowSel)}).filter({ hasText: updatedName }).first()).toBeVisible({ timeout: 15000 });`);
    put('  });');
    put('');
  }

  // ---- VALIDATION (grounded in Validators.required + the save gate) ----
  if (requiredFields.length && gate) {
    put(`  test('Validation: required fields gate the save button', async ({ page }) => {`);
    put(`    await ensureCapboSession(page, ${q(route)});`);
    put(`    await page.getByTestId(${q(createTid)}).click({ timeout: 15000 });`);
    put(`    // ${requiredFields.length} required control(s) from Validators.required → empty form must not be savable`);
    put(`    await expect(page.getByTestId(${q(saveTid)})).toBeDisabled({ timeout: 8000 });`);
    put(`    // Touch + clear the ${identityKey} field → required error must appear`);
    put(`    await fillAngularField(page, page.getByTestId(${q(identityTid)}), 'x');`);
    put(`    await fillAngularField(page, page.getByTestId(${q(identityTid)}), '');`);
    put(`    await page.keyboard.press('Tab');`);
    put(`    await expect(page.locator('mat-error').first()).toBeVisible({ timeout: 5000 });`);
    if (cancelTid) {
      put(`    await page.getByTestId(${q(cancelTid)}).click({ timeout: 8000 }).catch(() => {});`);
    }
    put('  });');
    put('');
  }

  // ---- DELETE ----
  if (deleteTid) {
    const target = editTid ? 'updatedName' : 'name';
    put(`  test('Delete ${feature}', async ({ page }) => {`);
    put(`    await ensureCapboSession(page, ${q(route)});`);
    put(`    await searchList(page, ${target}, ${searchOpts});`);
    if (editTid) {
      put(`    await page.locator(${q(rowSel)}).filter({ hasText: ${target} }).first().getByTestId(${q(editTid)}).or(page.getByTestId(${q(editTid)}).first()).first().click({ timeout: 10000 });`);
    } else {
      put(`    await page.locator(${q(rowSel)}).filter({ hasText: ${target} }).first().click({ timeout: 10000 });`);
    }
    put(`    await page.getByTestId(${q(deleteTid)}).click({ timeout: 10000 });`);
    if (confirmTid) {
      put(`    // Confirm dialog (testid from shared confirmation component)`);
      put(`    await page.getByTestId(${q(confirmTid)}).click({ timeout: 8000 });`);
    } else {
      put(`    await page.getByRole('button', { name: /confirm|confirmer|yes|oui/i }).first().click({ timeout: 8000 });`);
    }
    put(`    await searchList(page, ${target}, ${searchOpts});`);
    const gone = emptyTid
      ? `await expect(page.locator(${q(rowSel)}).filter({ hasText: ${target} }).first()).toBeHidden({ timeout: 15000 });`
      : `await expect(page.locator(${q(rowSel)}).filter({ hasText: ${target} }).first()).toBeHidden({ timeout: 15000 });`;
    put(`    ${gone}`);
    put('  });');
    put('');
  }

  put('});');
  put('');

  return {
    source: L.join('\n'),
    meta: {
      feature,
      route,
      stem,
      fields: fields.map((f) => ({ key: f.formControl, kind: f.kind, testId: f.testId, value: f.value })),
      requiredFields: requiredFields.map((f) => f.key),
      tests: {
        create: true,
        view: Boolean(viewTid),
        edit: Boolean(editTid),
        validation: Boolean(requiredFields.length && gate),
        delete: Boolean(deleteTid),
      },
      controls: { createTid, saveTid, editTid, viewTid, rowTid, deleteTid, searchTid, confirmTid, identityTid },
      verifyNeedle: resolveVerifyNeedle(prepared.testData, prepared.resolvedValues, schema),
    },
  };
}
